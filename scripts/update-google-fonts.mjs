#!/usr/bin/env node
// VibeDesign — regenerate lib/data/google-fonts.json
//
//   node scripts/update-google-fonts.mjs
//   node scripts/update-google-fonts.mjs --check     (CI: fail if stale)
//
// Writes the list of Google Fonts family NAMES ONLY. No files, no metrics, no
// URLs, no licence text — just the names, because the only question the
// extension asks is "is this family on Google Fonts?".
//
// Why names only: the extension ships every file it loads, and the full
// metadata payload is ~2.6 MB. The name list is a few tens of KB and answers
// the question exactly as well.
//
// Source: https://fonts.google.com/metadata/fonts — the endpoint the Google
// Fonts site itself calls. No API key, unlike the developer API, so this stays
// runnable by anyone with the repo.
//
// This is a BUILD-TIME script. It is never called from the extension: the
// extension reads the generated JSON, and makes no network request of its own.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'lib', 'data', 'google-fonts.json');
// The extension has no build step, so a classic <script> cannot read JSON off
// disk. The same data is therefore also emitted as a one-line JS wrapper that
// publishes a global. Both come from this script and never diverge by hand;
// tests/skill-bundle.test.js asserts they hold the identical list.
const OUT_JS = path.join(ROOT, 'lib', 'data', 'google-fonts.js');
const SOURCE = 'https://fonts.google.com/metadata/fonts';

async function fetchFamilies() {
  const res = await fetch(SOURCE, { headers: { accept: 'application/json' } });
  if (!res.ok) throw new Error(`${SOURCE} responded ${res.status}`);
  let body = await res.text();
  // The endpoint prefixes its JSON with an anti-hijacking guard on some paths.
  body = body.replace(/^\)\]\}'\n?/, '');
  const data = JSON.parse(body);

  const list = data.familyMetadataList;
  if (!Array.isArray(list) || !list.length) {
    throw new Error('familyMetadataList missing or empty — the response shape changed');
  }
  const families = list
    .map(f => f && f.family)
    .filter(f => typeof f === 'string' && f.trim())
    .map(f => f.trim());

  // Sorted and de-duplicated so the file is stable across runs and a diff shows
  // only what actually changed at Google's end.
  return [...new Set(families)].sort((a, b) => a.localeCompare(b, 'en'));
}

function render(families) {
  return JSON.stringify({
    $comment: 'Generated by scripts/update-google-fonts.mjs — do not edit by hand. '
      + 'Family names only; used to tell an openly-licensed family from a proprietary one.',
    source: SOURCE,
    count: families.length,
    families,
  }, null, 0) + '\n';
}

// The browser-loadable twin of the JSON. Same array, published as a global.
function renderJs(families) {
  return '// Generated by scripts/update-google-fonts.mjs — do not edit by hand.\n'
    + '// The browser-loadable twin of google-fonts.json: the extension has no build\n'
    + '// step, so a classic <script> cannot read the JSON. Family names only.\n'
    + 'const VD_GOOGLE_FONTS = ' + JSON.stringify(families) + ';\n'
    + 'if (typeof self !== \'undefined\') self.VD_GOOGLE_FONTS = VD_GOOGLE_FONTS;\n'
    + 'if (typeof module !== \'undefined\' && module.exports) module.exports = VD_GOOGLE_FONTS;\n';
}

async function main() {
  const check = process.argv.includes('--check');
  const families = await fetchFamilies();
  const next = render(families);

  // Sanity floor: Google Fonts has had well over a thousand families for years.
  // A truncated response that parsed cleanly would otherwise silently reclassify
  // every open font as proprietary.
  if (families.length < 1000) {
    throw new Error(`only ${families.length} families — refusing to write a suspiciously short list`);
  }
  for (const canary of ['Inter', 'Roboto', 'Instrument Sans', 'Chivo Mono']) {
    if (!families.includes(canary)) {
      throw new Error(`"${canary}" is missing — the response is not the full catalogue`);
    }
  }

  const nextJs = renderJs(families);
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  const currentJs = fs.existsSync(OUT_JS) ? fs.readFileSync(OUT_JS, 'utf8') : '';
  if (check) {
    if (current !== next || currentJs !== nextJs) {
      process.stderr.write('lib/data/google-fonts.json is stale — run: node scripts/update-google-fonts.mjs\n');
      process.exit(1);
    }
    process.stderr.write(`up to date (${families.length} families)\n`);
    return;
  }

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, next);
  fs.writeFileSync(OUT_JS, nextJs);
  process.stderr.write(`wrote ${path.relative(ROOT, OUT)} — ${families.length} families`
    + `, ${(next.length / 1024).toFixed(1)} KB\n`);
  process.stderr.write(`wrote ${path.relative(ROOT, OUT_JS)} — ${(nextJs.length / 1024).toFixed(1)} KB\n`);
  if (current && current !== next) {
    const before = JSON.parse(current).families || [];
    const added = families.filter(f => !before.includes(f));
    const removed = before.filter(f => !families.includes(f));
    process.stderr.write(`  +${added.length} / -${removed.length} since the last run\n`);
    if (added.length && added.length <= 12) process.stderr.write(`  added: ${added.join(', ')}\n`);
    if (removed.length) process.stderr.write(`  removed: ${removed.join(', ')}\n`);
  }
}

main().catch(err => {
  process.stderr.write(`\nupdate-google-fonts failed: ${err.message}\n`);
  process.exit(1);
});
